export function explainError(code) { return ERRORS[code] || 'The controller reported an error.'; }
export function explainAlarm(code) { const a = ALARMS[code]; return a ? { what: a[0], fix: a[1] } : { what: 'The controller raised an alarm.', fix: 'Press Unlock, or home the machine.' }; }

